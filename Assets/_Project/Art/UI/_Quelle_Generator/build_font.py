UNIT = 100
ASC = 8


def build():
    names = [".notdef"]
    cmap = {}
    glyphs = {}
    metrics = {}

    pen = TTGlyphPen(None)
    pen.moveTo((0, 0)); pen.lineTo((0, 700)); pen.lineTo((500, 700)); pen.lineTo((500, 0)); pen.closePath()
    pen.moveTo((100, 100)); pen.lineTo((400, 100)); pen.lineTo((400, 600)); pen.lineTo((100, 600)); pen.closePath()
    glyphs[".notdef"] = pen.glyph()
    metrics[".notdef"] = (600, 0)

    for ch, (top, rows) in G.items():
        name = "uni%04X" % ord(ch)
        names.append(name)
        cmap[ord(ch)] = name
        pen = TTGlyphPen(None)
        for r, row in enumerate(rows):
            gy = top + r
            y1 = (ASC - gy) * UNIT
            y0 = y1 - UNIT
            for x, c in enumerate(row):
                if c != "#":
                    continue
                x0, x1 = x * UNIT, (x + 1) * UNIT
                # Uhrzeigersinn (TrueType-Aussenkontur)
                pen.moveTo((x0, y0)); pen.lineTo((x0, y1)); pen.lineTo((x1, y1)); pen.lineTo((x1, y0)); pen.closePath()
        glyphs[name] = pen.glyph()
        metrics[name] = (600, 0)

    fb = FontBuilder(800, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=800, descent=-200, lineGap=0)
    fb.setupNameTable({"familyName": "Nightward Pixel", "styleName": "Regular"})
    fb.setupOS2(sTypoAscender=800, sTypoDescender=-200, sTypoLineGap=0, usWinAscent=800, usWinDescent=200,
                sxHeight=500, sCapHeight=700, fsType=0)
    fb.setupPost(isFixedPitch=1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    fb.save(OUT)
    # Gridfit/Hinting: kein Hinting noetig, alle Punkte liegen auf 100er-Raster
    print("Font:", os.path.abspath(OUT), len(cmap), "Zeichen")


if __name__ == "__main__":
    for ch, (top, rows) in G.items():
        for r in rows:
            assert len(r) == 5, (ch, r)
    build()
